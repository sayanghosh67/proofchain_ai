import { useState } from "react";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { useServerFn } from "@tanstack/react-start";
import { supabase } from "@/integrations/supabase/client";
import { askInvestigator } from "@/lib/product.functions";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { toast } from "sonner";
import type { ProjectData } from "./data";
type Message = {
  id: string;
  question: string;
  answer: string;
  evidence_ids: string[];
  model: string;
  created_at: string;
};
export function Investigator({ d }: { d: ProjectData }) {
  const ask = useServerFn(askInvestigator),
    qc = useQueryClient();
  const [question, setQuestion] = useState(""),
    [busy, setBusy] = useState(false);
  const { data: messages, error } = useQuery({
    queryKey: ["investigator", d.project.id],
    queryFn: async () => {
      const { data, error } = await (supabase as any)
        .from("investigator_messages")
        .select("*")
        .eq("project_id", d.project.id)
        .order("created_at");
      if (error) throw error;
      return data as Message[];
    },
  });
  return (
    <section className="glass space-y-4 p-5">
      <div>
        <h2 className="text-xl font-semibold">AI Audit Investigator</h2>
        <p className="mt-2 text-sm text-muted-foreground">
          Ask about this project's evidence, gaps, and saved findings. Answers are generated by
          Gemini and saved to your project.
        </p>
      </div>
      {error && (
        <p role="alert" className="text-destructive">
          Could not load conversation: {error.message}
        </p>
      )}
      <div className="max-h-[32rem] space-y-4 overflow-auto" aria-live="polite">
        {messages?.map((m) => (
          <article key={m.id} className="space-y-3 rounded-lg border border-border p-4">
            <p className="font-medium">{m.question}</p>
            <p className="whitespace-pre-wrap text-sm text-muted-foreground">{m.answer}</p>
            {m.evidence_ids.map((id) => (
              <p className="break-all text-xs text-primary" key={id}>
                Evidence: {d.evidence.find((e) => e.id === id)?.title ?? id} · {id}
              </p>
            ))}
            <p className="text-xs text-muted-foreground">
              {m.model} · {new Date(m.created_at).toLocaleString()}
            </p>
          </article>
        ))}
      </div>
      <form
        className="space-y-3"
        onSubmit={async (e) => {
          e.preventDefault();
          setBusy(true);
          try {
            await ask({ data: { projectId: d.project.id, question } });
            setQuestion("");
            await qc.invalidateQueries({ queryKey: ["investigator", d.project.id] });
          } catch (e) {
            toast.error((e as Error).message);
          } finally {
            setBusy(false);
          }
        }}
      >
        <Textarea
          required
          maxLength={2000}
          aria-label="Question for the audit investigator"
          placeholder="What evidence is missing for my milestones?"
          value={question}
          onChange={(e) => setQuestion(e.target.value)}
        />
        <Button disabled={busy || !question.trim() || !d.project.ai_consent}>
          {busy ? "Investigating…" : "Ask investigator"}
        </Button>
        {!d.project.ai_consent && (
          <p className="text-sm text-muted-foreground">
            Enable Gemini analysis in project permissions first.
          </p>
        )}
      </form>
    </section>
  );
}
